Un cookie est un petit fichier texte déposé sur votre terminal lors de la visite d'un site, conformément à la **Directive C/DIR.1/08/11 de la CEDEAO** sur la cybersécurité et à la **loi n°010-2004/AN** du Burkina Faso sur la protection des données personnelles.


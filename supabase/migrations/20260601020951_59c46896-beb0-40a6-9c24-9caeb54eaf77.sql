# Conditions Spécifiques — Equity & Vesting

**Dernière mise à jour :** 1er juin 2026

## 1. Objet

Les présentes conditions encadrent les mécanismes d'attribution d'actions, de BSPCE/BSA et de plans de vesting proposés via le simulateur Union'S, conformément à l'**Acte Uniforme OHADA relatif au droit des sociétés commerciales (AUSCGIE)** révisé en 2014.

## 2. Cadre juridique OHADA

### 2.1 Formes sociales adaptées
- **SAS OHADA** (recommandée pour startups) : flexibilité statutaire, actions de préférence autorisées.
- **SARL OHADA** : structure plus rigide, parts sociales uniquement.

### 2.2 Instruments d'equity
- **Actions ordinaires** (parts du capital social).
- **Actions de préférence** (avec droits financiers/politiques renforcés — AUSCGIE art. 778-1 et s.).
- **BSA** (Bons de Souscription d'Actions).
- **Obligations convertibles** (convertibles notes — AUSCGIE art. 822 et s.).
- **Equity-based compensation** : plans assimilés aux BSPCE français, à structurer via BSA réservés.

## 3. Cap Table & Simulateur

Le simulateur de cap table Union'S permet de :
- Modéliser la structure capitalistique pré et post-tour.
- Simuler des scénarios de dilution.
- Calculer l'impact d'une conversion d'obligations convertibles (avec valuation cap et discount).
- Visualiser l'exit waterfall (préférence de liquidation, participation).

**Limite de responsabilité :** les simulations sont indicatives et ne constituent ni un conseil juridique ni un conseil financier. Toute opération doit être validée par un **notaire** et un **avocat OHADA**.

## 4. Plans de Vesting

### 4.1 Principe
Le vesting (acquisition progressive) sécurise l'engagement des co-fondateurs et collaborateurs clés.

### 4.2 Schémas standards
- **4 ans avec cliff 1 an** : 25 % acquis après 1 an, puis acquisition linéaire mensuelle sur 36 mois.
- **3 ans sans cliff** : acquisition linéaire mensuelle.
- **Reverse vesting** : les fondateurs détiennent leurs actions dès J0 mais s'engagent à les rétrocéder en cas de départ avant terme.

### 4.3 Clauses associées
- **Bad leaver / Good leaver** : sort des titres en cas de départ fautif ou non fautif.
- **Acceleration** : vesting accéléré en cas de cession de contrôle (single/double trigger).
- **Tag-along / Drag-along** : protection des minoritaires et obligation de cession conjointe.

## 5. Pactes d'associés

Tout déploiement de plan de vesting doit s'accompagner d'un **pacte d'associés** notarié ou sous seing privé enregistré, comportant a minima :
- Préemption (ROFR).
- Inaliénabilité temporaire.
- Anti-dilution (full ratchet ou weighted average).
- Information renforcée des investisseurs.
- Clauses de sortie (liquidation preference, drag-along).

## 6. Formalités OHADA

Toute opération sur le capital (augmentation, réduction, émission de BSA) nécessite :
- Décision de l'AGE (Assemblée Générale Extraordinaire).
- Modification statutaire enregistrée au **RCCM**.
- Publication dans un journal d'annonces légales.
- Déclaration fiscale auprès de la **DGI** dans les 30 jours.

## 7. Fiscalité (Burkina Faso)

- Les plus-values de cession de titres sont imposables au taux de **27,5 %** (Code général des impôts BF, sous réserve de modifications).
- Les attributions d'equity-compensation peuvent constituer un avantage en nature soumis à cotisations CNSS et IUTS.
- Régimes d'exonération possibles pour les startups labellisées (à vérifier auprès de l'Agence nationale de promotion).

## 8. Responsabilité du simulateur

Le simulateur est un **outil pédagogique**. UNION'S SAS :
- Ne garantit pas l'exactitude juridique des structures proposées.
- N'agit pas en qualité de conseil en investissement.
- Recommande systématiquement le recours à un **avocat OHADA** et à un **notaire**.

## 9. Confidentialité des cap tables

Les cap tables simulées sont strictement privées et accessibles uniquement aux personnes invitées par le créateur. UNION'S SAS s'engage à un chiffrement AES-256 au repos.

## 10. Litiges

Tout litige relatif à la structuration d'un deal relève de l'arbitrage **CCJA-OHADA** ou du Tribunal de commerce de Ouagadougou.

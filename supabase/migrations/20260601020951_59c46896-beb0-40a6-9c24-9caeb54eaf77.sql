## 2. Conditions d'éligibilité

### 2.1 Investisseur qualifié
Pour accéder aux deals et syndicates, l'Investisseur doit :
- Être majeur (18 ans) et juridiquement capable.
- Compléter avec succès la procédure **KYC** (Know Your Customer).
- Justifier de sa qualité d'investisseur conformément au règlement général du CREPMF.

### 2.2 KYC obligatoire
Documents requis :
- Pièce d'identité en cours de validité (CNIB, passeport).
- Justificatif de domicile de moins de 3 mois.
- Pour les personnes morales : RCCM, statuts, liste des bénéficiaires effectifs (loi n°016-2016/AN LBC/FT).
- Déclaration sur l'honneur d'origine des fonds.

## 3. Syndicates et Deals

### 3.1 Nature des opérations
Les syndicates organisent des prises de participation collectives dans des sociétés cibles, structurées en **SAS** ou **SARL OHADA**. Chaque deal précise :
- La société cible et ses statuts.
- La valorisation pre-money et post-money.
- Les instruments utilisés (actions ordinaires, BSA, obligations convertibles).
- Les pactes d'associés (drag-along, tag-along, ROFR, anti-dilution).

### 3.2 Lead Investor
Le Lead Investor d'un syndicate est responsable de la négociation des termes, de la due diligence et de la coordination avec la société cible. Il agit en mandataire des co-investisseurs dans les limites définies au pacte.

### 3.3 Commitments
- Un engagement (commitment) constitue une **promesse ferme d'investissement** sous condition suspensive de finalisation du deal.
- Les fonds sont conservés en **escrow** jusqu'au closing.
- En cas de non-closing dans les délais, les fonds sont intégralement restitués sans frais.

## 4. Risques

L'investissement en startups comporte des risques substantiels :
- **Risque de perte totale** du capital investi.
- **Risque d'illiquidité** : les titres ne sont pas cotés.
- **Risque de dilution** lors de futurs tours.
- **Risque opérationnel** lié à l'exécution de la société cible.

L'Investisseur reconnaît avoir lu et compris ces risques, et investir uniquement des sommes dont la perte n'affecterait pas significativement sa situation financière.

## 5. Frais

- **Carry du syndicate** : généralement 20 % des plus-values (négocié au cas par cas).
- **Frais d'administration** : 2 % du montant investi à l'entrée.
- **Aucun frais caché** : tous les frais sont divulgués avant la signature.

## 6. LBC/FT — Lutte contre le blanchiment

Conformément à la **loi n°016-2016/AN du 3 mai 2016** relative à la LBC/FT au Burkina Faso et aux recommandations du **GIABA**, UNION'S SAS :
